import XCTest
import UIKit

final class InkDriveUITests: XCTestCase {
    override func setUp() { super.setUp(); continueAfterFailure = false }
    func testLibraryAndEditorWorkWithoutDevelopmentServer() throws {
        let app = XCUIApplication(); app.launchArguments = ["--ui-smoke"]; app.launch()
        XCUIDevice.shared.orientation = .landscapeLeft
        let landscape = XCTNSPredicateExpectation(predicate: NSPredicate { _, _ in app.frame.width > app.frame.height }, object: nil)
        XCTAssertEqual(XCTWaiter.wait(for: [landscape], timeout: 10), .completed)
        XCTAssertTrue(app.buttons["통계학"].waitForExistence(timeout: 12))
        XCTAssertFalse(app.buttons["새 수업 녹음"].exists)
        XCTAssertFalse(app.buttons["수업 연결"].exists)
        XCTAssertTrue(app.buttons["학교"].exists)
        attach("Swift library", app)
        app.buttons["새 문서 메뉴"].tap()
        XCTAssertTrue(app.buttons["새 폴더"].waitForExistence(timeout: 3))
        XCTAssertTrue(app.buttons["새 노트"].exists)
        attach("Creation menu", app)
        app.buttons["새 문서 메뉴"].tap()
        app.buttons["통계학"].tap()
        XCTAssertTrue(app.buttons["강의 1.pdf"].waitForExistence(timeout: 5))
        app.buttons["상위 폴더"].tap()
        XCTAssertTrue(app.buttons["작업설계"].exists)
        app.buttons["통계학"].tap(); app.buttons["강의 1.pdf"].tap()
        XCTAssertTrue(app.buttons["녹음 목록"].waitForExistence(timeout: 12))
        XCTAssertTrue(app.buttons["녹음 시작"].exists)
        XCTAssertTrue(app.buttons["펜"].exists)
        attach("Swift editor", app)
        app.buttons["펜"].tap()
        XCTAssertTrue(app.sliders["굵기 px"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.buttons["도구막대에서 빼기"].exists)
        attach("Anchored pen settings", app)
        app.buttons["연필 종류 선택"].tap()
        XCTAssertTrue(app.staticTexts["연필"].waitForExistence(timeout: 4))
        app.buttons["펜 종류 선택"].tap()
        XCTAssertTrue(app.staticTexts["펜"].waitForExistence(timeout: 4))
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.92, dy: 0.8)).tap()
        app.buttons["도구막대 방향 전환"].tap()
        attach("Vertical toolbar", app)
        app.buttons["도구막대 방향 전환"].tap()
        XCTAssertTrue(app.sliders["빠른 페이지 이동"].exists)
        app.buttons["녹음 목록"].tap()
        XCTAssertTrue(app.staticTexts["저장된 녹음 없음"].waitForExistence(timeout: 5))
        XCTAssertFalse(app.buttons["재생"].isEnabled)
        attach("Recording browser", app)
        app.buttons["필기로"].tap()
        app.buttons["페이지"].tap()
        XCTAssertTrue(app.buttons["목차·북마크·검색"].waitForExistence(timeout: 5))
        attach("Page overview", app)
        app.buttons["페이지 추가"].tap()
        attach("Unified paper menu", app)
        XCTAssertTrue(app.buttons["노란 줄노트"].waitForExistence(timeout: 3))
        app.buttons["노란 줄노트"].tap()
        XCTAssertTrue(app.collectionViews.cells["2 페이지"].waitForExistence(timeout: 5))
        attach("Inserted yellow page", app)
        app.collectionViews.cells["2 페이지"].tap()
        XCTAssertTrue(app.buttons["페이지"].waitForExistence(timeout: 5))
        attach("Yellow paper editor", app)
        app.buttons["보기 설정"].tap()
        XCTAssertTrue(app.buttons["한 페이지씩"].waitForExistence(timeout: 4))
        attach("Unified view settings", app)
        app.buttons["한 페이지씩"].tap()
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.72, dy: 0.6)).press(forDuration: 0.05, thenDragTo: app.coordinate(withNormalizedOffset: CGVector(dx: 0.3, dy: 0.6)))
        app.buttons["도구 추가"].tap()
        XCTAssertTrue(app.buttons["panel-action-펜"].waitForExistence(timeout: 4))
        attach("Add another pen", app)
        // The custom menu and toolbar both contain pens; choose the menu's last matching button.
        app.buttons["panel-action-펜"].tap()
        XCTAssertTrue(app.staticTexts["기본 색상"].waitForExistence(timeout: 4))
        app.buttons["색상 #E60012"].tap()
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.92, dy: 0.8)).tap()
        let penItems = app.buttons.matching(NSPredicate(format: "identifier BEGINSWITH %@", "toolbar-item-"))
        XCTAssertGreaterThan(penItems.count, 6)
        let moved = penItems.element(boundBy: penItems.count - 1)
        let movedID = moved.identifier
        moved.press(forDuration: 0.5, thenDragTo: penItems.element(boundBy: 0))
        XCTAssertEqual(penItems.element(boundBy: 0).identifier, movedID)
        attach("Independent colored pens reordered", app)
        app.buttons["페이지"].tap()
        app.buttons["목차·북마크·검색"].tap()
        XCTAssertTrue(app.buttons["목차"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.buttons["북마크"].exists)
        XCTAssertTrue(app.buttons["검색"].exists)
        attach("Page navigator", app)
        app.buttons["필기로"].tap()
        app.buttons["다른 문서 열기"].tap()
        XCTAssertTrue(app.cells.containing(.staticText, identifier: "강의 2").firstMatch.waitForExistence(timeout: 5))
        app.cells.containing(.staticText, identifier: "강의 2").firstMatch.tap()
        XCTAssertTrue(app.buttons["문서 탭 통계학/강의 2.pdf"].waitForExistence(timeout: 8))
        attach("Document tabs", app)
        app.buttons["서재로"].tap()
        XCTAssertTrue(app.buttons["강의 1.pdf"].waitForExistence(timeout: 10))
        app.buttons["상위 폴더"].tap()
        app.buttons["학교"].tap()
        XCTAssertTrue(app.buttons["지금 확인"].waitForExistence(timeout: 8))
        attach("Campus controls", app)
        app.buttons["서재"].tap()
        app.buttons["강의자료"].tap(); app.buttons["스냅샷.html"].tap()
        let snapshot = app.buttons["필기용 고정본"]
        XCTAssertTrue(snapshot.waitForExistence(timeout: 10))
        let ready = XCTNSPredicateExpectation(predicate: NSPredicate(format: "enabled == true"), object: snapshot)
        XCTAssertEqual(XCTWaiter.wait(for: [ready], timeout: 15), .completed)
        attach("HTML material", app); snapshot.tap()
        let returned = XCTNSPredicateExpectation(predicate: NSPredicate(format: "hittable == true"), object: app.buttons["상위 폴더"])
        XCTAssertEqual(XCTWaiter.wait(for: [returned], timeout: 10), .completed)
        app.buttons["상위 폴더"].tap(); app.buttons["Snapshots"].tap()
        let fixed = app.buttons.matching(NSPredicate(format: "label BEGINSWITH %@", "스냅샷_")).firstMatch
        XCTAssertTrue(fixed.waitForExistence(timeout: 8)); fixed.tap()
        XCTAssertTrue(app.buttons["펜"].waitForExistence(timeout: 10)); attach("HTML snapshot editor", app)
    }
    private func attach(_ name: String, _ app: XCUIApplication) {
        let attachment = XCTAttachment(screenshot: XCUIScreen.main.screenshot()); attachment.name = name; attachment.lifetime = .keepAlways; add(attachment)
    }
}
